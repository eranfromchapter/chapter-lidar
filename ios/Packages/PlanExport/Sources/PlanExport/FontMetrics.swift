  /// Width of `text` in points at `size` points (Times-Roman when `serif` is true).
  static func width(_ text: String, size: Double, bold: Bool = false, serif: Bool = false)
    -> Double
  {
    let table = serif ? Self.serif : bold ? Self.bold : Self.regular
    let fallback = serif ? 500 : 556
    var total = 0
    for scalar in text.unicodeScalars {
      let index = Int(scalar.value) - 0x20
      total += index >= 0 && index < table.count ? table[index] : fallback
    }
    return Double(total) * size / 1000
  }
}
