/// Advance widths of the PDF standard fonts Helvetica and Helvetica-Bold (WinAnsi), in
/// 1/1000 em, for the printable ASCII range. Other characters use a mean width.
enum FontMetrics {
  // Index 0 is U+0020 (space) through U+007E (~).
  private static let regular: [Int] = [
    278, 278, 355, 556, 556, 889, 667, 191, 333, 333, 389, 584, 278, 333, 278, 278,
    556, 556, 556, 556, 556, 556, 556, 556, 556, 556, 278, 278, 584, 584, 584, 556,
    1015, 667, 667, 722, 722, 667, 611, 778, 722, 278, 500, 667, 556, 833, 722, 778,
    667, 778, 722, 667, 611, 722, 667, 944, 667, 667, 611, 278, 278, 278, 469, 556,
    333, 556, 556, 500, 556, 556, 278, 556, 556, 222, 222, 500, 222, 833, 556, 556,
    556, 556, 333, 500, 278, 556, 500, 722, 500, 500, 500, 334, 260, 334, 584,
  ]

  private static let bold: [Int] = [
    278, 333, 474, 556, 556, 889, 722, 238, 333, 333, 389, 584, 278, 333, 278, 278,
    556, 556, 556, 556, 556, 556, 556, 556, 556, 556, 333, 333, 584, 584, 584, 611,
    975, 722, 722, 722, 722, 667, 611, 778, 722, 278, 556, 722, 611, 833, 722, 778,
    667, 778, 722, 667, 611, 722, 667, 944, 667, 667, 611, 333, 278, 333, 584, 556,
    333, 556, 611, 556, 611, 556, 333, 611, 611, 278, 278, 556, 278, 889, 611, 611,
    611, 611, 389, 556, 333, 611, 556, 778, 556, 556, 500, 389, 280, 389, 584,
  ]

  /// Width of `text` in points at `size` points.
  static func width(_ text: String, size: Double, bold: Bool = false) -> Double {
    let table = bold ? Self.bold : Self.regular
    var total = 0
    for scalar in text.unicodeScalars {
      let index = Int(scalar.value) - 0x20
      total += index >= 0 && index < table.count ? table[index] : 556
    }
    return Double(total) * size / 1000
  }
}
